const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const {validate,ROOT}=require('./validate');
function generate(slug) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) throw new Error('Invalid port slug');
  const d=JSON.parse(fs.readFileSync(path.join(ROOT,'ports',`${slug}.json`),'utf8'));
  const errors=validate(d,{strict:d.meta?.status==='researched'}); if(errors.length) throw new Error(errors.join('\n'));
  if(d.slug!==slug) throw new Error('Port filename and slug must match');
  const data='// Generated by npm run build. Edit ports/'+slug+'.json instead.\nwindow.PORT_DATA = '+JSON.stringify(d,null,2)+';\n';
  const manifest=JSON.stringify({name:`${d.port.name} Port Brief`,short_name:d.port.name,description:`Port brief for ${[d.port.name,d.port.country].filter(Boolean).join(', ')}.`,start_url:'./',scope:'./',display:'standalone',background_color:'#f7f3ea',theme_color:'#0a7ea4',icons:[{src:'icons/icon-192.png',sizes:'192x192',type:'image/png'},{src:'icons/icon-512.png',sizes:'512x512',type:'image/png'},{src:'icons/icon-maskable-512.png',sizes:'512x512',type:'image/png',purpose:'maskable'}]},null,2)+'\n';
  const hash=crypto.createHash('sha256').update(data).update(manifest);
  for(const f of ['index.html','app.js','styles.css','ashore.js','brief-tools.js','vendor/leaflet/leaflet.js','vendor/leaflet/leaflet.css','templates/sw.template.js','icons/icon-192.png','icons/icon-512.png','icons/icon-maskable-512.png','icons/apple-touch-icon.png']) hash.update(fs.readFileSync(path.join(ROOT,f)));
  const revision=hash.digest('hex').slice(0,16);
  const sw=fs.readFileSync(path.join(ROOT,'templates/sw.template.js'),'utf8').replaceAll('__REVISION__',revision);
  return {'data.js':data+'window.PORT_REVISION = '+JSON.stringify(revision)+';\n','manifest.webmanifest':manifest,'sw.js':sw};
}
if(require.main===module) {
  try {
    const slug=JSON.parse(fs.readFileSync(path.join(ROOT,'site.config.json'),'utf8')).port;
    const outputs=generate(slug),check=process.argv.includes('--check');
    for(const [file,content] of Object.entries(outputs)) {
      if(check) { if(fs.readFileSync(path.join(ROOT,file),'utf8')!==content) throw new Error(`${file} is stale; run npm run build`); }
      else fs.writeFileSync(path.join(ROOT,file),content);
    }
    console.log(`${check?'Checked':'Built'} ${slug}: ${Object.keys(outputs).join(', ')}`);
  } catch(e) {console.error(e.message);process.exitCode=1;}
}
module.exports={generate};
